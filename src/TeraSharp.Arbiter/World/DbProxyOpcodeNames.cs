    /// <summary>Name for <paramref name="op"/>, or null when it is not in the 0x2700-0x29FF table.</summary>
    public static string? Name(ushort op) => Names.TryGetValue(op, out var n) ? n : null;

    /// <summary>"0xNNNN NAME" for log lines; "0xNNNN" alone when the opcode is unknown.</summary>
    public static string Describe(ushort op)
    {
        var n = Name(op);
        return n is null ? $"0x{op:X4}" : $"0x{op:X4} {n}";
    }

    private static readonly IReadOnlyDictionary<ushort, string> Names = Parse(Table);

    private static Dictionary<ushort, string> Parse(string table)
    {
        var map = new Dictionary<ushort, string>(1024);
        foreach (var line in table.Split('\n'))
        {
            var s = line.Trim();
            if (s.Length == 0) continue;
            int bar = s.IndexOf('|');
            if (bar < 0) continue;
            map[Convert.ToUInt16(s[..bar], 16)] = s[(bar + 1)..];
        }
        return map;
    }

