        foreach (var row in Rows)
            if (keyword.Length == 0
                || row.Name.Contains(keyword, StringComparison.OrdinalIgnoreCase)
                || row.Arguments.Contains(keyword, StringComparison.Ordinal)
                || row.Description.Contains(keyword, StringComparison.Ordinal))
                yield return row;
    }
