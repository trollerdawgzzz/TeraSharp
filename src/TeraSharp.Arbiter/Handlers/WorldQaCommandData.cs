namespace TeraSharp.Arbiter.Handlers;

// =============================================================================================
// WorldQaCommandData - T233. WorldServer's own QA command table, extracted from the binary.
//
// These do NOT run here. The Arbiter forwards an unknown /@ command to World, and World's
// CommandDistributor::ProcessCommand looks the name up in this registry - logging
// "QA Command: %s" when it resolves and, via WorldCommandDistributor::OnUnregisteredCommand,
// "[QA] Invalid Command: %s" plus "Invalid QA Command" to the caller when it does not. The list
// is here so /@help can answer for World too: T201 forwarded "_helpworld <term>" for that, and
// _helpworld is NOT one of the 545 names below - it does not exist on this build, so the
// forward could only ever have produced "Invalid QA Command".
//
// Provenance: every FUN_140114090(registry, type, name, handler, flag, args, usage) call in
// world_decompiled/WorldServer.exe.c - 545 of them. The decompile declares the data symbols as
// bare "undefined DAT_...", so 7 names, 231 argument strings and 48 usage strings were read out
// of Executable/WorldServer.exe directly (image base 0x140000000, RVA via the section table,
// UTF-16LE). An empty Arguments means the registration passed &PTR_1419c2970, whose target is
// eight zero bytes - the "no arguments" sentinel, not a string we failed to resolve.
//
// Usage text is retail's own, in Korean, verbatim. It is the ground truth; any English in
// status/WORLD-QA-COMMANDS.md is a gloss and is marked as ours there.
//
// Type is WorldServer's CommandType argument. OnUnregisteredCommand labels type 0 "OP" and
// everything else "QA"; the registry only ever uses 1 (15 commands - the battlefield and cheat
// set) and 4 (530 - the bulk QA set). "bookmark" is registered under both.
// =============================================================================================
