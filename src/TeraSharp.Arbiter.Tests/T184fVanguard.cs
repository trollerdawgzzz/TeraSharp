    [Test] public static void T184fVanguard_reward_claim_is_a_World_owned_tunnel()
    {
        // cap_2man_client1 #10212: claim event2142; client2 never sends this action.
        // WorldServer.exe.c:573589-573646 Handler_C_COMPLETE_DAILY_EVENT looks up
        // EventMatching[frame+12], then completes its quest. Arbiter must not grant twice.
        var claim = Convert.FromHexString("1000BB4F01000000016934005E080000");
        Hex.True(!ArbiterClientHandlers.ArbiterOwned.Contains(0x4FBB), "claim uses the live World-forward fallback");
        var real = T184fVanguardFrame(8450)[6..];
        Hex.True(TunnelFrames.TryParseBypassToWorld(real, out ulong gameId, out ulong tick, out var forwarded), "tap8450 AS13F6");
        Hex.True(gameId == 0x80000AF00002UL && BitConverter.ToUInt32(claim, 12) == 2142, "correct character gameId and event");
        Hex.Eq(forwarded, claim, "the client claim is unchanged in AS13F6");
        Hex.Eq(TunnelFrames.BuildBypassToWorld(gameId, claim, tick), real, "whole captured World tunnel payload");
    }

    [Test] public static void T184fVanguard_claim_database_replies_and_rewards_persist()
    {
        // Actual cap_2man source records, with the original character1003. The existing
        // quest/item/reputation/EP handlers own persistence; World builds client rewards.
        using var store = GuildStore(1003);
        store.SetCharacterMoney(1003, 0);
        var handlers = FreshHandlers(store);
        (ushort op, byte[] body) Pair(int request, int response, bool allocatedItemIds = false, bool allocatedQuestId = false)
        {
            var req = T184fVanguardFrame(request);
            var real = T184fVanguardFrame(response);
            var got = RunHandler1(BitConverter.ToUInt16(req, 4), req[6..], store, handlers);
            Hex.True(got.op == BitConverter.ToUInt16(real, 4), $"tap{request}->{response} opcode");
            var expected = real[6..];
            // Database-generated IDs are state, not structure. Every other byte is pinned.
            if (allocatedItemIds)
                foreach (int atom in new[] { 1, 2 })
                    Array.Copy(got.body, 21 + atom * 856 + 16, expected, 21 + atom * 856 + 16, 4);
            if (allocatedQuestId) Array.Copy(got.body, 34, expected, 34, 4);
            Hex.Eq(got.body, expected, $"cap_2man {request}->{response}");
            return got;
        }

        Pair(8451, 8452); // 272E SQL23 complete ->272F; success, original80B quest record.
        Hex.True(store.GetCompletedQuestIds(1003).Contains(700029) && store.GetActiveQuestRecords(1003).Count == 0,
            "quest700029 is complete before repeat re-offer");
        Pair(8515, 8516); // end quest-start context2736->2737.
        Pair(8517, 8518); // reputation609, live record rather than a calculated reward.
        Hex.Eq(store.GetReputations(1003).Single(), T184fVanguardFrame(8517)[26..], "all52 reputation bytes persist");
        Pair(8521, 8522, allocatedItemIds: true);
        Hex.True(store.GetCharacterMoney(1003) == 12_500_000, "op9 grants captured money delta");
        var items = store.GetInventoryItems(1003);
        Hex.True(items.Any(i => i.TemplateId == 45474 && i.Amount == 1 && i.Slot == 42)
            && items.Any(i => i.TemplateId == 1300 && i.Amount == 30 && i.Slot == 43), "both op7 item grants persist");
        Pair(8533, 8534);
        var ep = store.GetCharacterEp(1003)!;
        var epRequest = T184fVanguardFrame(8533);
        Hex.True(ep.EpExp == BitConverter.ToInt64(epRequest, 14)
            && ep.EpLevel == BitConverter.ToInt32(epRequest, 22)
            && ep.EpPoint == BitConverter.ToInt32(epRequest, 26)
            && ep.DailyEpExp == BitConverter.ToInt32(epRequest, 30)
            && ep.ReserveBonus == BitConverter.ToInt32(epRequest, 34)
            && ep.DailyLimit == BitConverter.ToInt32(epRequest, 38), "all six EP fields persist");
        Pair(8544, 8545, allocatedQuestId: true);
        var active = store.GetActiveQuestRecords(1003).Single();
        Hex.True(BitConverter.ToInt32(active, 4) == 700029 && BitConverter.ToInt32(active, 8) == 1
            && BitConverter.ToInt32(active, 12) == 1 && !store.GetCompletedQuestIds(1003).Contains(700029),
            "repeat event returns to active quest700029, status1 step1");
    }

    [Test] public static void T184fVanguard_generated_id_builders_match_the_whole_real_reply()
    {
        int itemId = 10142;
        Hex.Eq(DbProxyHandlers.BuildDbs2769(T184fVanguardFrame(8521)[6..], () => itemId++),
            T184fVanguardFrame(8522)[6..], "all2589 payload bytes with real allocated item IDs10142/10143");
        Hex.Eq(DbProxyHandlers.BuildDbs2733(T184fVanguardFrame(8544)[6..], (_, _) => 1315),
            T184fVanguardFrame(8545)[6..], "all38 payload bytes with real repeat questDbId1315");
    }

